#!/usr/bin/env python3
"""Build the heatbox assembly guide as a self-contained HTML page, then a PDF.

Every diagram is a render of heatbox.scad and every mass is measured from the exported
STL, so the guide cannot drift from the part: regenerate the STLs and the numbers and
pictures in the PDF move with them. Nothing here is drawn or typed to look right.

    python3 make_guide.py            # writes doc/heatbox-assembly.html and .pdf

The PDF step shells out to headless Chrome, which is the only HTML-to-PDF engine on
this machine (no wkhtmltopdf, no pandoc). If Chrome is absent the HTML is still written
and the script says so rather than pretending a PDF exists.
"""
import base64
from pathlib import Path
import shutil
import subprocess
import sys

import mass

HERE = Path(__file__).resolve().parent
DOC = HERE / "doc"
OUT = HERE / "out"
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"

STEPS = [
    ("Print the four pieces",
     "step1",
     "One body, one deck, one lid, two caps. All five sit flat on the bed as exported "
     "and none needs support. The body is the long print; the other three are quick. "
     "Check the body's underside is a clean closed skirt before you carry on — the "
     "floor bridges across it, so a skirt that failed to stick means a sagged floor."),
    ("Drop the deck onto its ledges",
     "step2",
     "The deck falls into the box and lands on six stubs about a third of the way up. "
     "It only fits one way round: the end with the single spare hole goes to the right, "
     "away from the air inlet. Do not glue it. It lifts out for cleaning, and it is the "
     "piece you replace first if anything ever warps."),
    ("Fit the aluminium inlet tube",
     "step3",
     "Push the 20 mm bore aluminium tube through the round socket in the left-hand wall "
     "until about 25 mm stands inside the box. Three ribs inside the socket hold it; it "
     "should be a firm push, not a hammer fit. This tube exists so the hot air from your "
     "gun lands on metal instead of plastic, so never run the box without it."),
    ("Stand the two copper shoes in their pockets",
     "step4",
     "Each shoe stands upright between four corner ribs, resting on three small domes so "
     "air passes underneath. There is a finger of space at both ends of each pocket — "
     "that gap is for your tongs, so keep it clear."),
    ("Put the lid on",
     "step5",
     "The lid drops over the rim with its skirt inside the inner wall. Two rectangular "
     "slots line up over the two shoes; the two small round vents go to the right-hand "
     "end, the opposite end from the inlet."),
    ("Drop a cap over each slot",
     "step6",
     "Each cap sits on four small posts on the lid and is located by four pins. It is "
     "meant to sit slightly proud — the 2 mm gap all the way round is the chamber's "
     "exhaust, and closing it would pressurise the box. Lift a cap by its fin to take a "
     "shoe out; leave the other cap alone."),
]


def b64(path):
    return base64.b64encode(path.read_bytes()).decode()


def parts_table():
    rows = []
    for path in sorted(OUT.glob("heatbox_*.stl")):
        volume, _, box = mass.measure(path)
        grams = volume * mass.DENSITY
        copies = 2 if "_cap_" in path.name else 1
        rows.append((path.name.split("_")[1], copies, grams * copies,
                     " × ".join(f"{d:.0f}" for d in box)))
    return rows


