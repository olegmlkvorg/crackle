def main():
    DOC.mkdir(exist_ok=True)
    missing = [n for n in ["exploded", "cutaway"] + [s[1] for s in STEPS]
               if not (DOC / f"{n}.png").is_file()]
    if missing:
        print(f"missing renders: {missing}\n"
              "run the render loop in README.md first", file=sys.stderr)
        return 2
    if not list(OUT.glob("heatbox_*.stl")):
        print("no STLs in out/ — nothing to measure", file=sys.stderr)
        return 2

    html_path = DOC / "heatbox-assembly.html"
    html_path.write_text(build_html())
    print(f"wrote {html_path.relative_to(HERE)} ({html_path.stat().st_size/1024:.0f} KB)")

    if not Path(CHROME).exists() and shutil.which("google-chrome") is None:
        print("Chrome not found — HTML written, PDF NOT generated.", file=sys.stderr)
        return 1
    pdf_path = DOC / "heatbox-assembly.pdf"
    proc = subprocess.run(
        [CHROME, "--headless", "--disable-gpu", "--no-pdf-header-footer",
         f"--print-to-pdf={pdf_path}", html_path.as_uri()],
        capture_output=True, text=True, timeout=180)
    if not pdf_path.is_file() or pdf_path.stat().st_size < 20000:
        print("PDF missing or suspiciously small:\n" + proc.stderr[-800:], file=sys.stderr)
        return 1
    print(f"wrote {pdf_path.relative_to(HERE)} "
          f"({pdf_path.stat().st_size/1024:.0f} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
